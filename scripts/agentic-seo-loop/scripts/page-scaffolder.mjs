#!/usr/bin/env node
/**
 * w4 — page scaffolder.
 *
 * Reads new-page-proposals.jsonl. For each proposal:
 *   1. Resolve/normalize the slug (must be kebab-case, /topics/ prefix)
 *   2. Skip if src/pages/topics/<slug>/index.jsx already exists
 *   3. Write a minimal component with:
 *        - <SEO> block (title, description, canonical)
 *        - <h1>{proposed_h1}</h1>
 *        - outline stub — one <section><h2>...</h2></section> per outline item
 *        - JSON-LD script matching proposed_json_ld_type
 *   4. Register the route in src/App.jsx as a lazy import
 *   5. Register the route in scripts/enumerate-routes.mjs
 *   6. Register the route in scripts/generate-sitemap.js
 *
 * We treat App.jsx / enumerate-routes.mjs / generate-sitemap.js as append-only
 * for our own bookkeeping — a sentinel comment marks the round-4 block so
 * re-runs don't duplicate lines.
 */

import fs from 'node:fs';
import path from 'node:path';

const args = Object.fromEntries(process.argv.slice(2)
  .map(a => a.startsWith('--') ? a.slice(2).split('=') : [a, true])
  .map(([k, v]) => [k, v === undefined ? true : v]));

const REPO = args.repo || process.env.JEDI_V2_REPO || '/workspace/jedi-v2';
const RUN_DIR = args['run-dir'];
if (!RUN_DIR) { console.error('--run-dir required'); process.exit(2); }

const proposalsPath = path.join(RUN_DIR, 'new-page-proposals.jsonl');
if (!fs.existsSync(proposalsPath)) {
  console.error(`missing ${proposalsPath}`); process.exit(2);
}
// S3 FUSE quirk: reading a truly-empty file can EPERM. Stat first, treat
// size=0 as "no proposals" without triggering the read.
const stat = fs.statSync(proposalsPath);
const raw = stat.size === 0 ? '' : fs.readFileSync(proposalsPath, 'utf8').trim();
const proposals = raw ? raw.split('\n').filter(Boolean).map(l => JSON.parse(l)) : [];
console.log(`[scaffolder] ${proposals.length} new-page proposals`);

const applied = [];
const dropped = [];

const kebab = (s) => (s || '')
  .toLowerCase()
  .replace(/[^\w\s-]/g, ' ')
  .replace(/\s+/g, '-')
  .replace(/-+/g, '-')
  .replace(/^-|-$/g, '');

const pascal = (s) => (s || '')
  .split(/[^\w]+/)
  .filter(Boolean)
  .map(w => w[0].toUpperCase() + w.slice(1))
  .join('');

const escapeJsAttr = (s) => (s || '')
  .replace(/\\/g, '\\\\')
  .replace(/"/g, '\\"')
  .replace(/\n/g, ' ')
  .trim();

const sanitizeOutline = (outline, keyword) => {
  if (Array.isArray(outline) && outline.length) {
    return outline
      .map(x => (typeof x === 'string' ? x : (x?.title || x?.h2 || '')).trim())
      .filter(Boolean)
      .slice(0, 6);
  }
  return [
    `What ${keyword} means in production`,
    `Where ${keyword} fails today`,
    `How Jedi Labs approaches ${keyword}`,
    `Getting started with ${keyword}`,
  ];
};

function generatePageJsx(p, slug) {
  const outline = sanitizeOutline(p.proposed_outline, p.target_keyword);
  const title = escapeJsAttr(p.proposed_title || `${p.target_keyword} | Jedi Labs Research`);
  const desc = escapeJsAttr(p.rationale ? `${p.rationale.split('.')[0]}.` : `Insight on ${p.target_keyword} in production AI.`);
  const h1 = p.proposed_h1 || p.proposed_title || p.target_keyword;
  const ldType = ['TechArticle', 'Article', 'FAQPage', 'HowTo'].includes(p.proposed_json_ld_type)
    ? p.proposed_json_ld_type : 'TechArticle';
  const canonical = `https://jedilabs.org/topics/${slug}`;
  const compName = pascal(slug) + 'Topic';

  const ldObj = {
    '@context': 'https://schema.org',
    '@type': ldType,
    headline: p.proposed_title || p.target_keyword,
    description: desc,
    url: canonical,
    author: { '@type': 'Organization', name: 'Jedi Labs' },
    publisher: { '@type': 'Organization', name: 'Jedi Labs', url: 'https://jedilabs.org' },
  };

  return `// AUTOGENERATED by agentic-seo-loop (round 4). Safe to edit — sentinel below tracks provenance.
/* seo:round4:scaffold:/topics/${slug} */
import React from 'react';
import SEO from '@/components/SEO';

export default function ${compName}() {
  return (
    <>
      <SEO
        title="${title}"
        description="${desc}"
        canonical="${canonical}"
        ogType="article"
      />
      <script
        type="application/ld+json"
        dangerouslySetInnerHTML={{ __html: JSON.stringify(${JSON.stringify(ldObj, null, 2).split('\n').map(l => '        ' + l).join('\n').trim()}) }}
      />
      <article className="mx-auto max-w-3xl px-6 py-16">
        <h1 className="text-4xl font-bold leading-tight mb-6">${h1}</h1>
        <p className="text-lg text-gray-700 mb-10">${desc}</p>
${outline.map(sec => `        <section className="mb-8">
          <h2 className="text-2xl font-semibold mb-3">${sec}</h2>
          <p className="text-base text-gray-700">Placeholder — expand this section with Jedi Labs' point of view on <em>${sec.toLowerCase()}</em>. Draft by editorial before merging.</p>
        </section>`).join('\n')}
      </article>
    </>
  );
}
`;
}

function appendRouteToApp(slug, compName) {
  const appPath = path.join(REPO, 'src/App.jsx');
  if (!fs.existsSync(appPath)) return { ok: false, reason: 'no-App.jsx' };
  let content = fs.readFileSync(appPath, 'utf8');
  const sentinel = `/* seo:round4:route-registered:/topics/${slug} */`;
  if (content.includes(sentinel)) return { ok: true, note: 'already-registered' };

  // Find the last existing `<Route ...>` line inside the router; append near it.
  // Fallback: append near the closing </Routes>.
  const importLine = `const ${compName} = React.lazy(() => import('./pages/topics/${slug}/index.jsx'));`;
  const routeLine = `<Route path="/topics/${slug}" element={<${compName} />} /> ${sentinel}`;

  // Insert import at the first `import React` line
  const importRx = /import React[^;]*;/;
  if (importRx.test(content) && !content.includes(importLine)) {
    content = content.replace(importRx, (m) => `${m}\n${importLine}`);
  }
  // Insert route just before </Routes>
  const routesCloseRx = /(<\/Routes>)/;
  if (routesCloseRx.test(content)) {
    content = content.replace(routesCloseRx, `        ${routeLine}\n        $1`);
  } else {
    return { ok: false, reason: 'no-Routes-closing-tag' };
  }
  fs.writeFileSync(appPath, content);
  return { ok: true, note: 'registered' };
}

function appendToEnumerator(slug) {
  const enumPath = path.join(REPO, 'scripts/enumerate-routes.mjs');
  if (!fs.existsSync(enumPath)) return { ok: false, reason: 'no-enumerator' };
  let content = fs.readFileSync(enumPath, 'utf8');
  const marker = `/* seo:round4:enum:/topics/${slug} */`;
  if (content.includes(marker)) return { ok: true, note: 'already-listed' };

  // enumerate-routes emits an array of static routes; look for a
  // `staticRoutes` or `routes` array and push to it via a trailing block.
  // We handle it by appending an idempotent block at end of file that
  // exports the extras — the enumerator merges them.
  const suffix = `
${marker}
try {
  if (typeof staticRoutes !== 'undefined' && Array.isArray(staticRoutes) && !staticRoutes.includes('/topics/${slug}')) {
    staticRoutes.push('/topics/${slug}');
  }
} catch (e) { /* enumerator layout changed — no-op */ }
`;
  fs.writeFileSync(enumPath, content + suffix);
  return { ok: true, note: 'appended-block' };
}

function appendToSitemap(slug) {
  const smPath = path.join(REPO, 'scripts/generate-sitemap.js');
  if (!fs.existsSync(smPath)) return { ok: false, reason: 'no-sitemap-script' };
  let content = fs.readFileSync(smPath, 'utf8');
  const marker = `/* seo:round4:sitemap:/topics/${slug} */`;
  if (content.includes(marker)) return { ok: true, note: 'already-listed' };
  const suffix = `
${marker}
try {
  if (typeof extraRoutes !== 'undefined' && Array.isArray(extraRoutes)) {
    if (!extraRoutes.includes('/topics/${slug}')) extraRoutes.push('/topics/${slug}');
  }
} catch (e) { /* sitemap script layout changed — no-op */ }
`;
  fs.writeFileSync(smPath, content + suffix);
  return { ok: true, note: 'appended-block' };
}

for (const p of proposals) {
  const rawRoute = p.proposed_route || '';
  if (!rawRoute.startsWith('/topics/')) {
    // Coerce anything else into /topics/<kebab>
    const forced = '/topics/' + kebab(p.proposed_route || p.target_keyword || '');
    p.proposed_route = forced;
  }
  const slug = p.proposed_route.replace(/^\/topics\//, '').replace(/\/$/, '');
  if (!slug || !/^[a-z0-9-]+$/.test(slug)) {
    dropped.push({ target_keyword: p.target_keyword, reason: 'bad-slug', slug });
    continue;
  }

  const targetDir = path.join(REPO, 'src/pages/topics', slug);
  const targetIdx = path.join(targetDir, 'index.jsx');
  if (fs.existsSync(targetIdx)) {
    dropped.push({ target_keyword: p.target_keyword, reason: 'already-exists', route: p.proposed_route });
    continue;
  }
  fs.mkdirSync(targetDir, { recursive: true });
  const jsx = generatePageJsx(p, slug);
  fs.writeFileSync(targetIdx, jsx);

  const appRes = appendRouteToApp(slug, pascal(slug) + 'Topic');
  const enumRes = appendToEnumerator(slug);
  const smRes = appendToSitemap(slug);

  applied.push({
    route: p.proposed_route,
    file: path.relative(REPO, targetIdx),
    target_keyword: p.target_keyword,
    confidence: p.confidence,
    app_register: appRes,
    enumerator: enumRes,
    sitemap: smRes,
  });
  console.log(`[scaffolder] ✓ ${p.proposed_route} (${slug})`);
}

const out = path.join(RUN_DIR, 'pages-scaffolded.jsonl');
fs.writeFileSync(out, applied.map(a => JSON.stringify(a)).join('\n') + (applied.length ? '\n' : ''));
console.log(`[scaffolder] applied=${applied.length} dropped=${dropped.length}`);
console.log(`[scaffolder] dropped: ${JSON.stringify(dropped)}`);
console.log(`[scaffolder] artifact → ${out}`);
